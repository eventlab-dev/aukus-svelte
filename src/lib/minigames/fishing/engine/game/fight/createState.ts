import { FIGHT, TEMPERAMENTS, VIEW, type FishSpecies } from '../../config'
import { temperamentFor } from '../../fish'
import { clamp } from '../../utils'
import { buildScript } from '../behaviors'
import { ESCAPE_HOLD, FIGHT_RADIUS } from './constants'
import type { FightState } from './state'
import type { MinigameOptions } from './types'
import { weightLoad } from './weight'

/** Fresh mutable state for one fight, before the model starts its first tick. */
export function createFightState(fish: FishSpecies, options: MinigameOptions): FightState {
	const temperament = temperamentFor(fish)
	const mood = TEMPERAMENTS[temperament]
	return {
		fish,
		centerX: clamp(options.anchor.x, FIGHT_RADIUS + 8, VIEW.width - FIGHT_RADIUS - 8),
		centerY: clamp(options.anchor.y, FIGHT_RADIUS + 44, VIEW.height - FIGHT_RADIUS - 8),
		load: weightLoad(fish, options.weightKg),
		temperament,
		tempo: mood.tempo,
		runPower: mood.run,
		tirePower: mood.tire,
		recoveryPower: mood.recovery,
		feintChance: mood.feint,
		escapeHold: ESCAPE_HOLD * mood.escape,
		recoveryRate: Math.max(0.012, FIGHT.recoveryBase - fish.resistance * FIGHT.recoveryScale),
		fishX: 0,
		fishY: 0,
		vx: 0,
		vy: 0,
		targetX: 0,
		targetY: 0,
		script: buildScript(fish),
		moveIndex: 0,
		current: null,
		moveTime: 0,
		moveStartAngle: 0,
		moveStartRadius: 0,
		escapeAngle: 0,
		lastAngle: 0,
		warnTime: 0,
		warnAngle: 0,
		warnRest: 0,
		feintActive: false,
		feintTimer: 0,
		feintAngle: 0,
		feintHasRevealed: false,
		turnFlashValue: 0,
		endurance: 1,
		grip: 1,
		gripLock: 0,
		advantage: 0,
		counterWindow: 0,
		counterDelay: 0,
		counterSpan: 0,
		counterAngle: 0,
		counterArmed: false,
		counterPrepared: false,
		counterUsed: false,
		counterPending: false,
		counterFlash: 0,
		stickGrabAngle: null,
		stun: 0,
		preBurstAngle: null,
		lastSteerAngle: null,
		ready: false,
		lastReadyChime: -Infinity,
		sameAimTime: 0,
		lastAimAngle: null,
		feintPending: false,
		lastRunPending: false,
		lastRunUsed: false,
		lastRunRolled: false,
		hold: false,
		freshPress: false,
		finalCooldown: 0,
		pointerX: null,
		pointerY: null,
		pressX: null,
		pressY: null,
		directionX: 0,
		directionY: 0,
		steeringNow: false,
		neglect: 0,
		stickyX: 0,
		stickyY: 0,
		bubbles: [],
		bubbleTimer: 0,
		running: true,
		outside: false,
		outsideTimer: 0,
		escapeLock: 0,
		escapeFill: 0,
		elapsed: 0,
		finishResult: null,
		onWarn: options.onWarn,
		onCounter: options.onCounter,
		onReady: options.onReady,
		onResist: options.onResist,
		onGripOut: options.onGripOut
	}
}
